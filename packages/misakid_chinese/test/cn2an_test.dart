void _expectCases(
  Cn2AnNormalizer normalizer,
  List<(String input, String expected)> cases,
) {
  test('matches fixed original-library outputs', () {
    for (final (input, expected) in cases) {
      expect(normalizer.normalize(input), expected, reason: 'input: `$input`');
    }
  });
}
