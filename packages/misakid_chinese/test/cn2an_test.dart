      final zeroes4300 = '0' * 4300;
      final zeroes4301 = '${zeroes4300}0';

      expect(normalizer.normalize('-$zeroes4300'), '负零');
      expect(normalizer.normalize('-$zeroes4301'), '-$zeroes4301');
      expect(normalizer.normalize('$zeroes4300.5'), '零点五');
      expect(normalizer.normalize('$zeroes4301.5'), '$zeroes4301.5');
    });

