      final zeroes4301 = '${zeroes4300}0';

      expect(normalizer.normalize(zeroes4300), '零');
      expect(normalizer.normalize('${zeroes4299}1'), '一');
      expect(normalizer.normalize(zeroes4301), zeroes4301);
      expect(normalizer.normalize('${zeroes4300}1'), '${zeroes4300}1');
    });

