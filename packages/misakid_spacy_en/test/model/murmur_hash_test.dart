import 'package:misakid_spacy_en/src/model/model.dart';
import 'package:test/test.dart';

void main() {
  test('matches Thinc 8.3.4 uint64 hash keys for every model seed', () {
    const signedIds = <int>[
      0,
      1,
      -1,
      -9223372036854775808,
      81985529216486895,
      -81985529216486896,
    ];
    for (final entry in _oracle.entries) {
      final actual = <List<int>>[
        for (final value in signedIds)
          murmurHash3X86_128Uint64(value, entry.key),
      ];
      expect(actual, entry.value, reason: 'seed ${entry.key}');
    }
  });

  test('rejects values outside the uint32 seed domain', () {
    expect(() => murmurHash3X86_128Uint64(0, -1), throwsRangeError);
    expect(() => murmurHash3X86_128Uint64(0, 0x100000000), throwsRangeError);
  });
}

