/// Exact pinned Cutlet mapping for one kana, digraph, or symbol.
String? japaneseCutletMapping(String value) => _hepburn[value];

/// Number of exact entries in the pinned runtime table.
int get japaneseCutletMappingCount => _hepburn.length;

/// Ordered entries exposed only from this internal library for integrity QA.
Iterable<MapEntry<String, String>> get japaneseCutletMappingEntries =>
    _hepburn.entries;

/// Values from the 164 phonetic entries before pinned symbol mappings begin.
Iterable<String> get japaneseCutletPhoneticMappingValues =>
    _hepburn.entries.take(164).map((entry) => entry.value);

